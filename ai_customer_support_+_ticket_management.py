def predict_priority(message, sentiment, intent):

    text = message.lower()

    high_keywords = [
        "fraud",
        "hacked",
        "stolen",
        "urgent",
        "emergency",
        "charged twice",
        "money deducted",
        "account blocked",
        "cannot access",
        "very angry"
    ]

    medium_keywords = [
        "late",
        "failed",
        "problem",
        "issue",
        "not received",
        "incorrect",
        "wrong"
    ]

    if any(word in text for word in high_keywords):
        return "High"

    if sentiment == "Negative" and intent in [
        "Payment",
        "Refund",
        "Account"
    ]:
        return "High"

    if any(word in text for word in medium_keywords):
        return "Medium"

    return "Low"

