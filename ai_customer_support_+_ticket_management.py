def update_ticket_status(
    ticket_id,
    new_status
):

    allowed_status = [
        "Open",
        "In Progress",
        "Resolved",
        "Closed"
    ]

    if new_status not in allowed_status:

        return "Invalid status."

    conn = sqlite3.connect(
        DB_PATH
    )

    cursor = conn.cursor()

    cursor.execute(
        """
        UPDATE tickets
        SET status = ?
        WHERE ticket_id = ?
        """,
        (
            new_status,
            ticket_id
        )
    )

    conn.commit()

    rows_updated = cursor.rowcount

    conn.close()

    if rows_updated == 0:

        return "Ticket not found."

    return (
        f"Ticket {ticket_id} "
        f"updated to {new_status}."
    )

