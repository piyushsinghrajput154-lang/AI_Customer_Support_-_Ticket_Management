def build_context(results):

    context = ""

    for i, result in enumerate(results, 1):

        context += f"""
FAQ {i}
Question: {result['question']}
Answer: {result['answer']}
Category: {result['category']}
Similarity: {result['score']:.3f}
"""

    return context

