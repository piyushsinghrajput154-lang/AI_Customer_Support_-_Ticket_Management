def customer_support(
    name,
    email,
    message
):

    # -------------------------
    # INPUT VALIDATION
    # -------------------------

    if not name or not name.strip():
        name = "Guest"

    if not email or not email.strip():
        email = "Not Provided"

    if not message or not message.strip():

        return """
### ⚠️ Missing Message

Please enter your question or problem.
"""

    # -------------------------
    # CREATE TICKET
    # -------------------------

    result = create_ticket(
        customer_name=name,
        email=email,
        message=message
    )

    # -------------------------
    # ERROR HANDLING
    # -------------------------

    if result is None:

        return """
### ❌ Ticket Creation Failed

We could not create your support ticket.

Please try again.
"""

    # -------------------------
    # OUTPUT
    # -------------------------

    output = f"""
### 🤖 AI Customer Support

**Ticket ID:** `{result['ticket_id']}`

**Category:** {result['category']}

**Sentiment:** {result['sentiment']}

**Priority:** {result['priority']}

**Status:** Open

---

### 💬 AI Response

{result['ai_response']}

---

✅ Your issue has been successfully recorded
in the support system.
"""

    return output

